#!/usr/bin/env node
// Scans workforce/skills/*/meta.json and generates
// workforce/lambdas/shared/skill-registry-generated.ts — the static
// SKILL_REQUIRES map (per-skill credential requirements).
//
// ADR-0005 (single execution model): there is no skill-shape axis and no
// Lambda runner, so this script no longer emits a deterministic handler
// dispatch table. The only generated artefact is SKILL_REQUIRES, consumed
// by the orchestrator-tick CCR batch dispatch to resolve project
// credentials per task.
//
// Contract:
//   - Every skill folder contributes one SKILL_REQUIRES entry from its
//     meta.json:requires[] (defaulting to [] when omitted).
//   - The generated file is committed to git. CI runs this script and
//     asserts no diff (workforce:skill-registry:check).
//
// Invocation:
//   node workforce/scripts/build-skill-registry.mjs        # writes file
//   node workforce/scripts/build-skill-registry.mjs --check # exits 1 if diff

import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = fileURLToPath(new URL(".", import.meta.url));
const WORKFORCE_ROOT = join(HERE, "..");
const REPO_ROOT = join(WORKFORCE_ROOT, "..");
const SKILLS_DIR = join(WORKFORCE_ROOT, "skills");
const OUT_PATH = join(WORKFORCE_ROOT, "lambdas", "shared", "skill-registry-generated.ts");

const checkMode = process.argv.includes("--check");

function listSkillDirs() {
  if (!existsSync(SKILLS_DIR)) return [];
  return readdirSync(SKILLS_DIR)
    .filter((name) => statSync(join(SKILLS_DIR, name)).isDirectory())
    .filter((name) => /^[a-z][a-z0-9-]*$/.test(name))
    .sort();
}

const skillRequires = []; // { name, requires: string[] } for ALL skills
const commonsSkills = []; // names whose meta.json declares commons:true (Epic-021 §B.1)
for (const name of listSkillDirs()) {
  const metaPath = join(SKILLS_DIR, name, "meta.json");
  if (!existsSync(metaPath)) continue;
  let meta;
  try {
    meta = JSON.parse(readFileSync(metaPath, "utf8"));
  } catch (err) {
    console.error(`build-skill-registry: ${relative(REPO_ROOT, metaPath)} — ${err.message}`);
    process.exit(2);
  }

  // Every skill gets a SKILL_REQUIRES entry — the orchestrator-tick CCR
  // batch dispatch reads this to resolve project credentials for each task
  // in the batch. An empty `requires[]` is a valid entry; a missing
  // `requires` field defaults to []. (The skill-meta schema lints this.)
  const requires = Array.isArray(meta.requires) ? [...meta.requires] : [];
  skillRequires.push({ name, requires });

  // Epic-021 §B.1: the commons class is declared on the skill (meta.commons)
  // and generated into a set here, so the idle-talent detector reads a
  // derived list rather than carrying hand-written skill names (Q3).
  if (meta.commons === true) commonsSkills.push(name);
}

const requiresEntries = skillRequires
  .map(({ name, requires }) => {
    const list = requires.length === 0
      ? "[]"
      : `[${requires.map((r) => `"${r}"`).join(", ")}] as const`;
    return `  "${name}": ${list},`;
  })
  .join("\n");

const commonsEntries = commonsSkills.map((name) => `  "${name}",`).join("\n");

const content = `// THIS FILE IS GENERATED by workforce/scripts/build-skill-registry.mjs.
// DO NOT EDIT BY HAND. Run \`npm run workforce:skill-registry\` after
// adding or removing a skill, or changing a skill's requires[] / commons flag.
//
// Source:
//   SKILL_REQUIRES — workforce/skills/*/meta.json (.requires[] for ALL skills,
//                    defaulting to [] when omitted; consumed by orchestrator-tick
//                    CCR batch dispatch to resolve project credentials per task)
//   COMMONS_SKILLS — workforce/skills/*/meta.json (.commons === true; Epic-021
//                    §B.1 — the baseline cadence every persona shares, discounted
//                    by the idle-talent detector in the performance-reducer walk)

export const SKILL_REQUIRES: Record<string, readonly string[]> = {
${requiresEntries}
};

/** Skills whose executions do NOT count as specialised work (Epic-021 §B.1).
 *  Generated from meta.commons so the detector never hard-codes a name list. */
export const COMMONS_SKILLS: ReadonlySet<string> = new Set([
${commonsEntries}
]);
`;

if (checkMode) {
  const existing = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, "utf8") : "";
  if (existing !== content) {
    console.error(
      `build-skill-registry: ${relative(REPO_ROOT, OUT_PATH)} is stale. ` +
        `Run \`npm run workforce:skill-registry\` and commit the result.`,
    );
    process.exit(1);
  }
  console.log(
    `build-skill-registry: OK (${skillRequires.length} skill(s) with requires map, ` +
      `${commonsSkills.length} commons)`,
  );
  process.exit(0);
}

writeFileSync(OUT_PATH, content);
console.log(
  `build-skill-registry: wrote ${skillRequires.length} skill requires entries ` +
    `+ ${commonsSkills.length} commons -> ${relative(REPO_ROOT, OUT_PATH)}`,
);
