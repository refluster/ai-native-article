#!/usr/bin/env node
// Scans workforce/skills/*/meta.json and generates
// workforce/lambdas/shared/skill-registry-generated.ts — a static
// import-map of deterministic handlers, so adding a new deterministic
// skill is "drop a folder under workforce/skills/{name}/" (Mac
// Applications-style) with no lambdas/ edits.
//
// Contract:
//   - For every skill whose meta.json:executor === "deterministic",
//     this script asserts a sibling handler.ts exists and adds an
//     `export const REGISTRY` entry pointing at its default
//     `dispatch{PascalName}` export (e.g. discord-ping → dispatchDiscordPing).
//   - llm-prose / claude-code-routine skills are ignored — they're
//     interpreted by the runner without a per-skill handler.
//   - The generated file is committed to git. CI runs this script and
//     asserts no diff (workforce:skill-registry:check).
//
// Invocation:
//   node workforce/scripts/build-skill-registry.mjs        # writes file
//   node workforce/scripts/build-skill-registry.mjs --check # exits 1 if diff

import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = fileURLToPath(new URL(".", import.meta.url));
const WORKFORCE_ROOT = join(HERE, "..");
const REPO_ROOT = join(WORKFORCE_ROOT, "..");
const SKILLS_DIR = join(WORKFORCE_ROOT, "skills");
const OUT_PATH = join(WORKFORCE_ROOT, "lambdas", "shared", "skill-registry-generated.ts");

const checkMode = process.argv.includes("--check");

function pascalCase(name) {
  return name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function listSkillDirs() {
  if (!existsSync(SKILLS_DIR)) return [];
  return readdirSync(SKILLS_DIR)
    .filter((name) => statSync(join(SKILLS_DIR, name)).isDirectory())
    .filter((name) => /^[a-z][a-z0-9-]*$/.test(name))
    .sort();
}

const deterministicSkills = [];
for (const name of listSkillDirs()) {
  const metaPath = join(SKILLS_DIR, name, "meta.json");
  if (!existsSync(metaPath)) continue;
  let meta;
  try {
    meta = JSON.parse(readFileSync(metaPath, "utf8"));
  } catch (err) {
    console.error(`build-skill-registry: ${relative(REPO_ROOT, metaPath)} — ${err.message}`);
    process.exit(2);
  }
  if (meta.executor !== "deterministic") continue;

  const handlerPath = join(SKILLS_DIR, name, "handler.ts");
  if (!existsSync(handlerPath)) {
    console.error(
      `build-skill-registry: skill "${name}" has executor=deterministic but ` +
        `${relative(REPO_ROOT, handlerPath)} is missing. ` +
        `Add a handler.ts that exports dispatch${pascalCase(name)}.`,
    );
    process.exit(2);
  }
  deterministicSkills.push(name);
}

const importLines = deterministicSkills
  .map((name) => `import { dispatch${pascalCase(name)} } from "../../skills/${name}/handler.js";`)
  .join("\n");

const registryEntries = deterministicSkills
  .map((name) => `  "${name}": dispatch${pascalCase(name)},`)
  .join("\n");

const content = `// THIS FILE IS GENERATED by workforce/scripts/build-skill-registry.mjs.
// DO NOT EDIT BY HAND. Run \`npm run workforce:skill-registry\` after
// adding, removing, or changing the executor of a skill.
//
// Source: workforce/skills/*/meta.json (executor === "deterministic")

import type { DeterministicHandler } from "./skill-types.js";
${importLines ? "\n" + importLines + "\n" : ""}
export const DETERMINISTIC_HANDLERS: Record<string, DeterministicHandler> = {
${registryEntries}
};
`;

if (checkMode) {
  const existing = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, "utf8") : "";
  if (existing !== content) {
    console.error(
      `build-skill-registry: ${relative(REPO_ROOT, OUT_PATH)} is stale. ` +
        `Run \`npm run workforce:skill-registry\` and commit the result.`,
    );
    process.exit(1);
  }
  console.log(
    `build-skill-registry: OK (${deterministicSkills.length} deterministic skill(s))`,
  );
  process.exit(0);
}

writeFileSync(OUT_PATH, content);
console.log(
  `build-skill-registry: wrote ${deterministicSkills.length} deterministic skill(s) -> ${relative(REPO_ROOT, OUT_PATH)}`,
);
